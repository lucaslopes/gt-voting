"""Core functionality for generating honest reports from baselines."""

from math import factorial
import numpy as np
from core.rankings_core import generate_rankings, candidate_labels
from core.utils import spawn_rng


def parse_baselines(baselines_str, m, n=None):
    """
    Parse baseline string supporting both old and new syntax.
    
    Old syntax: "0,1,2,0,1,2" (comma-separated permutation indices)
    New syntax: "0*5,3*5,4*5" (permutation_index*count, expands to repeated indices)
    
    Baseline indices refer to positions in the sorted list of all possible rankings
    generated by generate_rankings(m) from core.rankings_core.
    
    Args:
        baselines_str: Baseline string in either format
        m: Number of candidates (to validate permutation index range)
        n: Optional expected number of voters (if None, will be inferred from baselines)
    
    Returns:
        Tuple (baselines_list, inferred_n) where:
        - baselines_list: List of permutation indices (length inferred_n)
        - inferred_n: Number of voters inferred from baselines
    """
    if baselines_str is None or baselines_str.strip() == "":
        return None, n
    
    try:
        baselines = []
        parts = [p.strip() for p in baselines_str.split(",")]
        
        for part in parts:
            if "*" in part:
                # New syntax: "index*count"
                if part.count("*") != 1:
                    raise ValueError(f"Invalid repetition syntax in '{part}'. Expected format: 'index*count'")
                
                idx_str, count_str = part.split("*")
                idx = int(idx_str.strip())
                count = int(count_str.strip())
                
                if count < 1:
                    raise ValueError(f"Repetition count must be >= 1, got {count} in '{part}'")
                
                baselines.extend([idx] * count)
            else:
                # Old syntax: single index
                baselines.append(int(part))
        
        inferred_n = len(baselines)
        
        # If n was provided, validate it matches
        if n is not None and inferred_n != n:
            raise ValueError(f"Expected {n} baseline indices (one per voter), got {inferred_n} from baselines string")
        
        # Validate that indices are within valid range
        n_perms = factorial(m)
        for i, idx in enumerate(baselines):
            if idx < 0 or idx >= n_perms:
                raise ValueError(f"Baseline index {idx} for voter {i} is out of range. "
                               f"Valid range: 0 to {n_perms-1} (for m={m} candidates, there are {n_perms} permutations)")
        
        return baselines, inferred_n
    except ValueError as e:
        raise ValueError(f"Invalid baselines format: {e}. "
                        f"Expected comma-separated integers (e.g., '0,1,2,0,1,2') "
                        f"or repetition syntax (e.g., '0*5,3*5,4*5')")


def baseline_indices_to_rankings(baseline_indices, m):
    """
    Convert baseline indices to actual ranking tuples.
    
    Baseline indices refer to positions in the sorted list returned by generate_rankings(m).
    
    Args:
        baseline_indices: List of baseline permutation indices
        m: Number of candidates
    
    Returns:
        List of ranking tuples, one per baseline index
    """
    all_rankings = generate_rankings(m, alphabetical=False)
    return [all_rankings[idx] for idx in baseline_indices]


def format_rankings_readable(rankings, m):
    """
    Convert rankings to readable format (e.g., ["A>B>C", "B>C>A", ...]).
    
    Args:
        rankings: List of ranking tuples (integer tuples)
        m: Number of candidates
    
    Returns:
        List of readable strings (e.g., ["A>B>C", "B>C>A", ...])
    """
    labels = candidate_labels(m)
    readable = []
    for ranking in rankings:
        # Convert tuple of indices to string like "A>B>C"
        ranking_str = ">".join(labels[c] for c in ranking)
        readable.append(ranking_str)
    return readable


def generate_honest_reports(m, n, baselines=None, seed=None, rng=None):
    """
    Generate honest reports from baselines or seed.
    
    If baselines are provided (list of indices), they are mapped to actual rankings.
    If baselines is None, rankings are sampled uniformly from all possible rankings using seed/rng.
    
    Args:
        m: Number of candidates
        n: Number of voters
        baselines: Optional list of baseline permutation indices (length n), or None for random sampling
        seed: Random seed for reproducibility (used if baselines is None)
        rng: Optional numpy Generator (if None, creates new one from seed)
    
    Returns:
        List of ranking tuples (same format as generate_rankings), one per voter
    """
    all_rankings = generate_rankings(m, alphabetical=False)
    n_perms = len(all_rankings)
    
    if baselines is not None:
        # Use provided baselines (indices)
        if len(baselines) != n:
            raise ValueError(f"Number of baseline indices ({len(baselines)}) doesn't match number of voters ({n})")
        
        # Validate indices
        for i, idx in enumerate(baselines):
            if idx < 0 or idx >= n_perms:
                raise ValueError(f"Baseline index {idx} for voter {i} is out of range. "
                               f"Valid range: 0 to {n_perms-1}")
        
        # Map indices to rankings
        honest_reports = baseline_indices_to_rankings(baselines, m)
    else:
        # Sample uniformly from all rankings
        rng = spawn_rng(seed, rng)
        sampled_indices = rng.choice(n_perms, size=n)
        honest_reports = [all_rankings[idx] for idx in sampled_indices]
    
    return honest_reports
